#!/usr/bin/env bash

set -euo pipefail

###############################################################################
# Paths
###############################################################################

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

ROOT_DIR="$(cd -- "${SCRIPT_DIR}/../.." && pwd)"

###############################################################################
# Files
###############################################################################

LIBRARY_CONFIG_FILE="${ROOT_DIR}/library.yaml"

###############################################################################
# Logging
###############################################################################

info()
{
    echo "[INFO] $*"
}

warn()
{
    echo "[WARN] $*" >&2
}

error()
{
    echo "[ERROR] $*" >&2
    exit 1
}

###############################################################################
# Validation
###############################################################################

require_file()
{
    [[ -f "$1" ]] || error "File not found: $1"
}

require_directory()
{
    [[ -d "$1" ]] || error "Directory not found: $1"
}

###############################################################################
# Helper
###############################################################################

command_exists()
{
    command -v "$1" >/dev/null 2>&1
}
